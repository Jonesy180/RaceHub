/* OTG! MAIN v8.0.206 — Festival-native relay selector and in-app route lock prompt.
 * UI-only patch: no storage writes, draw changes, race history edits or career honours.
 */
(function(){'use strict';
  const ID='otg-relay-festival-8202';
  const esc=s=>String(s??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
  function openRelay(mode){
    const planner=window.rhEvil2RelayPlanner186;
    if(!planner||typeof planner.show!=='function'){
      announce('Relay Race Control has not loaded. Nothing was changed.');return;
    }
    try{
      planner.show();
      const screen=document.getElementById('erc-194');
      if(!screen||screen.style.display==='none')throw new Error('Race Control did not open');
      const tab=screen.querySelector('[data-mode="'+mode+'"]');
      if(!tab)throw new Error('Requested relay is unavailable');
      tab.click();
      ['erc-back','erc-back-bottom'].forEach(id=>{
        const button=screen.querySelector('#'+id);
        if(button)button.textContent='← BACK TO FESTIVAL';
      });
    }catch(e){announce('Relay could not open: '+String(e.message||e)+'. No saved data changed.');}
  }
  function announce(message){
    let el=document.getElementById('otg-relay-toast-8202');
    if(!el){el=document.createElement('div');el.id='otg-relay-toast-8202';el.setAttribute('role','status');el.setAttribute('aria-live','polite');document.body.append(el);}
    el.textContent=message;el.hidden=false;
    clearTimeout(el._timer);el._timer=setTimeout(()=>{el.hidden=true;},6500);
  }
  function mount(){
    const festival=document.getElementById('festival');
    if(!festival||festival.classList.contains('hidden')||!festival.children.length)return;
    if(festival.querySelector('#'+ID))return;
    // Remove only prior v8.0.201 relay launcher, not the festival's native controls.
    festival.querySelector('#otg-relay-festival-8201')?.remove();
    // A native <details>/<summary> avoids the legacy global button hover/active
    // background styling that rendered the custom button grey on phones.
    const section=document.createElement('details');
    section.id=ID;
    section.className='otg-relay-festival-compact-8202';
    section.innerHTML='<summary id="otg-relay-toggle-8202" class="otg-relay-toggle-8202">'+
      '<span class="otg-relay-title-8202">RELAY COMPETITIONS</span><span class="otg-relay-chevron-8202" aria-hidden="true">⌄</span></summary>'+
      '<div id="otg-relay-choices-8202" class="otg-relay-choices-8202">'+
      '<button type="button" data-relay-8202="maker"><strong>🏁 OPEN RELAY RACE CONTROL</strong><small>Choose Manufacturer or Mixed at the top of Race Control</small><span aria-hidden="true" class="otg-relay-row-chevron-8202">❯</span></button>'+
      '<p class="otg-relay-qa-8202">Existing isolated relay QA competitions; official records and medals are not yet enabled.</p></div>';
    // Position the relay accordion immediately above the existing Festival
    // guidance card, not below it. Do not alter the guidance or the native lists.
    const locateGuide=()=>{
      const walker=document.createTreeWalker(festival,NodeFilter.SHOW_TEXT);
      let node;
      while((node=walker.nextNode())){
        if(!node.textContent.includes('Championships are generated from the cars in your Garage.'))continue;
        let el=node.parentElement;
        if(!el||el.closest('#'+ID))continue;
        // Find the smallest self-contained guidance panel, rather than the
        // whole Festival root. Content is generated by legacy Festival code.
        let candidate=el;
        while(candidate.parentElement&&candidate.parentElement!==festival){
          const parent=candidate.parentElement;
          const all=parent.textContent||'';
          if(parent.querySelector('button') && all.length>750)break;
          if(all.length>850)break;
          candidate=parent;
        }
        return candidate;
      }
      return null;
    };
    const guide=locateGuide();
    if(guide&&guide.parentNode)guide.parentNode.insertBefore(section,guide);
    else festival.append(section);
    // Expansion now belongs to native details; no custom state or button flash.
    section.querySelectorAll('[data-relay-8202]').forEach(b=>b.addEventListener('click',()=>openRelay(b.dataset.relay8202)));
  }
  function start(){
    const festival=document.getElementById('festival');if(festival){
      let pending=false;
      const queue=()=>{if(pending)return;pending=true;requestAnimationFrame(()=>{pending=false;mount();});};
      new MutationObserver(queue).observe(festival,{childList:true,attributes:true,attributeFilter:['class']});
      document.addEventListener('click',e=>{if(e.target.closest?.('[data-screen="festival"]'))queue();},{passive:true});
      queue();
    }
    installRouteDialog();
  }
  function installRouteDialog(){
    const allowed=new WeakSet();
    let active=null;
    function close(){
      if(!active)return;
      const {overlay,trigger}=active;active=null;overlay.remove();
      if(trigger.isConnected)trigger.focus({preventScroll:true});
    }
    document.addEventListener('click',function capture(e){
      const trigger=e.target.closest?.('#er197-lock-group');
      if(!trigger||allowed.has(trigger)){if(trigger)allowed.delete(trigger);return;}
      // The original lock handler belongs to the established v8.0.197 code.
      // Intercept only this exact button; never bypass storage validation.
      e.preventDefault();e.stopImmediatePropagation();
      if(active)return;
      const routeBox=trigger.closest('.er197-lock');
      const routes=[...(routeBox?.querySelectorAll('.er197-route-list > div')||[])].slice(0,3).map((row,i)=>({stage:i+1,name:row.querySelector('b')?.textContent||'Unknown',type:row.querySelector('small')?.textContent||''}));
      if(routes.length!==3){announce('Cannot display the three routes. Lock cancelled; no changes made.');return;}
      const overlay=document.createElement('div');
      overlay.className='otg-route-backdrop-8202';
      overlay.innerHTML='<div class="otg-route-dialog-8202" role="dialog" aria-modal="true" aria-labelledby="otg-route-dialog-title-8202" aria-describedby="otg-route-dialog-help-8202">'+
        '<h2 id="otg-route-dialog-title-8202">🔒 Lock these three routes?</h2><p id="otg-route-dialog-help-8202">This group will use these same routes for every team. Once locked, they cannot be redrawn.</p>'+
        '<div class="otg-route-list-dialog-8202">'+routes.map(r=>'<div><span>STAGE '+r.stage+'</span><strong>'+esc(r.name)+'</strong><small>'+esc(r.type)+'</small></div>').join('')+'</div>'+
        '<div class="otg-route-actions-8202"><button type="button" data-lock-action="cancel">CANCEL</button><button type="button" data-lock-action="confirm">🔒 CONFIRM &amp; LOCK</button></div></div>';
      document.body.append(overlay);active={overlay,trigger};
      const cancel=overlay.querySelector('[data-lock-action="cancel"]');
      const approve=overlay.querySelector('[data-lock-action="confirm"]');
      cancel.addEventListener('click',close);
      approve.addEventListener('click',()=>{
        close();
        if(!trigger.isConnected)return;
        // Existing handler calls native confirm() synchronously. Scoped to this
        // single validated click dispatch; restored immediately in finally.
        const nativeConfirm=window.confirm;
        try{
          allowed.add(trigger);
          window.confirm=()=>true;
          trigger.click();
        }finally{window.confirm=nativeConfirm;allowed.delete(trigger);}
      });
      overlay.addEventListener('keydown',ev=>{
        if(ev.key==='Escape'){ev.preventDefault();close();}
        if(ev.key==='Tab'){
          const items=[cancel,approve];const i=items.indexOf(document.activeElement);
          if(ev.shiftKey&&i===0){ev.preventDefault();approve.focus();}
          else if(!ev.shiftKey&&i===1){ev.preventDefault();cancel.focus();}
        }
      });
      approve.focus();
    },true);
  }
  if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',start,{once:true});else start();
})();
